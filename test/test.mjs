import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {loadCore,getTiles,getScene,render,persist,restore} from '../src/host.mjs';
const api=await loadCore();
assert.equal(api.kijo_version(),1);
assert.equal(getScene(api,'focus').length,4);
assert.equal(getScene(api,'overview').length,36);
let tiles=getTiles(api);
assert.equal(tiles.filter(t=>t.kind===2).length,3);
assert.equal(tiles[2*6+2].id,1);
assert.match(render(api,{view:'focus'}),/GHOST/);
assert.match(render(api,{view:'overview'}),/AGENT/);
const id=api.kijo_promote_ghost(1,1);
assert.equal(id,100);
assert.equal(getTiles(api)[7].kind,1);
assert.equal(getTiles(api)[7].owner,0);
assert.equal(api.kijo_close(1),1);
tiles=getTiles(api);
assert.equal(tiles[7].id,100,'independently promoted tile must survive close');
assert.equal(tiles[8].kind,0,'owned ghost cleaned');
assert.equal(tiles[13].kind,0,'owned ghost cleaned');
assert.equal(tiles[4].id,2,'unrelated tile preserved');
assert.equal(api.kijo_close(1),0,'cannot close same tile twice');
assert.equal(api.kijo_status(id,3),1);
assert.equal(getTiles(api)[7].status,3);
const temp=mkdtempSync(join(tmpdir(),'kijo-'));
const file=join(temp,'state.json');
persist(api,{100:'Permanent research note'},file);
api.kijo_reset();
assert.equal(getTiles(api)[7].kind,2);
const notes=restore(api,file);
assert.equal(getTiles(api)[7].id,100);
assert.equal(notes[100],'Permanent research note');
rmSync(temp,{recursive:true,force:true});
console.log('PASS — WASM layout, scene generation, overview, ownership, state, persistence');
