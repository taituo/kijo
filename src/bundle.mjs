#!/usr/bin/env node
// Builds the two zero-install artifacts:
//   dist/kijo.html   the whole browser app in ONE file (wasm, shaders, modules inlined)
//   dist/kijod.mjs   the optional relay in ONE file, with kijo.html embedded, runnable from stdin:
//                    ssh -L 7501:127.0.0.1:7501 host 'node --input-type=module -' < dist/kijod.mjs
// No bundler dependency: our modules use plain `import {..} from` / `export` forms, handled here.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = p => readFileSync(resolve(root, p), 'utf8');
const WEB = ['web/fonts.mjs', 'src/core.mjs', 'src/canvas.mjs', 'src/telemetry.mjs', 'web/injectors.mjs', 'web/daemon.mjs', 'src/vt.mjs', 'web/telemetry-draw.mjs', 'web/terminal.mjs', 'web/textsel.mjs', 'web/displaylist.mjs', 'web/surface3d.mjs', 'web/gpu.mjs', 'web/canvas2d.mjs', 'web/main.mjs'];
const strip = src => src
  .replace(/^import\s[^;]+;\s*$/gm, '')
  .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
  .replace(/^export\s+(?=(async\s+)?function|const|let|class)/gm, '');

export function bundle() {
  const code = WEB.map(p => `// ---- ${p}\n` + strip(read(p))).join('\n');
  if (/^\s*(import|export)\s/m.test(code)) throw new Error('bundle: unhandled import/export form');
  const embed = {};
  for (const p of ['core/scene.wasm.b64', 'shaders/scene.wgsl', 'shaders/heatmap.wgsl', 'shaders/surface.wgsl']) embed[p] = read(p);
  const json = JSON.stringify(embed).replace(/</g, '\\u003c');
  return read('web/index.html').replace('<script type="module" src="./main.mjs"></script>',
    `<script>globalThis.KIJO_EMBED=${json};</script>\n<script type="module">\n${code.replace(/<\/script/gi, '<\\/script')}\n</script>`);
}

export function bundleDaemon() {
  const ui = bundle();
  const modules = ['src/telemetry.mjs', 'src/kijod.mjs'].map(p => `// ---- ${p}\n` + read(p).replace(/^#!.*\n/, ''));
  // keep node: imports (deduped, hoisted); drop relative imports; drop exports
  const nodeImports = new Set(), body = modules.map(src => strip(src.replace(/^import\s[^;]*from\s+'node:[^']+';\s*$/gm, m => { nodeImports.add(m.trim()); return ''; }))).join('\n');
  if (/^\s*(import|export)\s/m.test(body)) throw new Error('bundleDaemon: unhandled import/export form');
  return `#!/usr/bin/env node\n// kijod ${'single-file build'} - generated by src/bundle.mjs, do not edit.\n${[...nodeImports].join('\n')}\nglobalThis.__KIJOD_BUNDLED__ = true;\nglobalThis.__KIJO_UI__ = ${JSON.stringify(ui).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')};\n${body}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(resolve(root, 'dist'), { recursive: true });
  const html = bundle(), d = bundleDaemon();
  writeFileSync(resolve(root, 'dist/kijo.html'), html); writeFileSync(resolve(root, 'dist/kijod.mjs'), d);
  console.log(`dist/kijo.html  ${(html.length / 1024).toFixed(1)} KB\ndist/kijod.mjs  ${(d.length / 1024).toFixed(1)} KB (includes the UI)`);
}
